#!/usr/bin/env python3
"""Validate Chinese translation files and write a progress report."""
import json, os, glob, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "data", "entries.json")
TRANS = os.path.join(ROOT, "data", "translations")
OUT = os.path.join(ROOT, "translation", "PROGRESS.md")

data = json.load(open(DATA, encoding="utf-8"))
entries = {e["id"]: e for e in data["entries"] if not e.get("xref")}
rows = []
errors = []

for path in sorted(glob.glob(os.path.join(TRANS, "*.json"))):
    tid = os.path.basename(path)[:-5]
    try:
        t = json.load(open(path, encoding="utf-8"))
    except Exception as exc:
        errors.append((tid, "JSON: " + str(exc)))
        continue
    e = entries.get(tid)
    if not e:
        errors.append((tid, "unknown or see-reference id"))
        continue
    items = t.get("body") or []
    if len(items) != len(e["body"]):
        errors.append((tid, f"body {len(items)} != source {len(e['body'])}"))
        continue
    bad = None
    for i, (item, src) in enumerate(zip(items, e["body"])):
        if item.get("i") != i:
            bad = f"index {item.get('i')} at position {i}"; break
        if item.get("type") != src.get("type"):
            bad = f"type mismatch at {i}"; break
        if not str(item.get("zh") or "").strip():
            bad = f"empty zh at {i}"; break
    if bad:
        errors.append((tid, bad)); continue
    zh = "".join(str(x.get("zh") or "") for x in items)
    cjk = len(re.findall(r"[\u4e00-\u9fff]", zh))
    arrows_src = sum(src.get("text", "").count("→") for src in e["body"])
    arrows_zh = zh.count("→")
    rows.append({
        "id": tid,
        "title": e["title"],
        "title_zh": t.get("title_zh", ""),
        "paragraphs": len(items),
        "cjk": cjk,
        "arrows_src": arrows_src,
        "arrows_zh": arrows_zh,
    })

rows.sort(key=lambda r: r["title"])
translated_paragraphs = sum(r["paragraphs"] for r in rows)
total_paragraphs = sum(len(e["body"]) for e in entries.values())
translated_cjk = sum(r["cjk"] for r in rows)

print(f"translated entries: {len(rows)} / {len(entries)}")
print(f"translated paragraphs: {translated_paragraphs} / {total_paragraphs}")
print(f"Chinese characters: {translated_cjk:,}")
print(f"errors: {len(errors)}")
for x in errors:
    print("  ERROR", x)

report = []
report.append("# Chinese translation progress\n")
report.append(f"Generated by `scripts/audit_translations.py`.\n")
report.append(f"- **Entries:** {len(rows)} / {len(entries)}")
report.append(f"- **Paragraphs:** {translated_paragraphs} / {total_paragraphs}")
report.append(f"- **Chinese characters:** {translated_cjk:,}")
report.append(f"- **Validation errors:** {len(errors)}\n")
report.append("## Translated entries\n")
report.append("| Entry | 中文标题 | Paragraphs | 汉字 | → source / zh |")
report.append("|---|---|---:|---:|---:|")
for r in rows:
    report.append(f"| {r['title']} | {r['title_zh']} | {r['paragraphs']} | {r['cjk']:,} | {r['arrows_src']} / {r['arrows_zh']} |")
if errors:
    report.append("\n## Errors\n")
    for tid, msg in errors:
        report.append(f"- `{tid}`: {msg}")
report.append("\n## Remaining\n")
missing = [e["title"] for e in entries.values() if e["id"] not in {r["id"] for r in rows}]
report.append(f"{len(missing)} entries still to translate. The next batch should prioritise the most-viewed entries and the motion pilot.\n")
open(OUT, "w", encoding="utf-8").write("\n".join(report))
print("wrote", OUT)
